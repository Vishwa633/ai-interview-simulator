BEGIN;

-- This schema is used by FastAPI; it does not need to be exposed via Supabase's Data API.
CREATE SCHEMA IF NOT EXISTS interviewloop;

CREATE TABLE IF NOT EXISTS interviewloop.feedback (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
    rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment text NOT NULL CHECK (char_length(comment) BETWEEN 1 AND 1000)
);

ALTER TABLE interviewloop.feedback ADD COLUMN IF NOT EXISTS author_id uuid;
ALTER TABLE interviewloop.feedback ENABLE ROW LEVEL SECURITY;

COMMIT;
